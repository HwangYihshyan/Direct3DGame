int TerrainTile::GetOpaqueBottom(
    const std::wstring& texturePath,
    int col,
    int row
)
{
    if (col < 0 || col >= COLS || row < 0 || row >= ROWS)
    {
        return TILE;
    }

    if (texturePath.find(L"terrain_forest") != std::wstring::npos)
    {
        return FOREST[row][col];
    }

    if (texturePath.find(L"terrain_plain") != std::wstring::npos)
    {
        return PLAIN[row][col];
    }

    if (texturePath.find(L"terrain_suburb") != std::wstring::npos)
    {
        return SUBURB[row][col];
    }

    return TILE;
}
